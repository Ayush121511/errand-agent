"""Run all scenarios offline and generate the eval table.

    uv run python -m evals.run            # all scenarios
    uv run python -m evals.run S09 S15    # a subset

Writes docs/eval_results.md (the table) and evals/results.json. `pytest` runs the same
scenarios and writes the same files at the end of the session.
"""

from __future__ import annotations

import json
import sys
import time
import traceback
from datetime import datetime
from pathlib import Path
from typing import Any

from evals.invariants import ALL, check_all
from evals.scenarios import REGISTRY, Scenario

ROOT = Path(__file__).resolve().parent.parent
MD_PATH = ROOT / "docs" / "eval_results.md"
JSON_PATH = ROOT / "evals" / "results.json"


def run_scenario(s: Scenario) -> dict[str, Any]:
    t0 = time.perf_counter()
    try:
        sr = s.fn()
        checks = [{"name": n, "ok": ok, "detail": d, "kind": "scenario"}
                  for n, ok, d in sr.checks]
        checks += [{"name": c.name, "ok": c.ok, "detail": c.detail, "kind": "invariant"}
                   for c in check_all(sr.h)]
        actual, notes = sr.actual, sr.notes
    except Exception as e:  # noqa: BLE001 - a crashing scenario is a failed scenario
        checks = [{"name": "scenario ran without exception", "ok": False,
                   "detail": "".join(traceback.format_exception_only(e)).strip(),
                   "kind": "scenario"}]
        actual, notes = f"crashed: {type(e).__name__}", traceback.format_exc(limit=3)
    failed = [c for c in checks if not c["ok"]]
    n_inv = sum(c["kind"] == "invariant" for c in checks)
    summary = f"{len(checks) - len(failed)}/{len(checks)} checks ({n_inv} global invariants)"
    if failed:
        summary += " — FAILED: " + "; ".join(f"{c['name']}: {c['detail'][:120]}" for c in failed)
    if notes and not failed:
        summary += f"; {notes}"
    return {
        "id": s.id, "name": s.name, "category": s.category, "expected": s.expected,
        "actual": actual, "passed": not failed, "notes": summary, "checks": checks,
        "duration_ms": round((time.perf_counter() - t0) * 1000, 1),
    }


def _cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_report(results: list[dict[str, Any]]) -> None:
    results = sorted(results, key=lambda r: r["id"])
    passed = sum(r["passed"] for r in results)
    lines = [
        "# Eval results",
        "",
        f"Generated by the test run on {datetime.now().strftime('%Y-%m-%d %H:%M')} "
        "(offline, scripted model, seeded mocks). Do not edit by hand.",
        "",
        f"**{passed}/{len(results)} scenarios passed.** Each scenario's checks include its own "
        f"assertions plus {len(ALL)} global invariants computed from ground truth (provider call "
        "log and state, agent DB, trace): no side effect without a valid user approval; no "
        "duplicate bookings; no success claim without verification; every run ends with a "
        "user-facing outcome; hard limits never exceeded; every context within the token "
        "budget; no forgotten/superseded/unconfirmed memory reaches the model; untrusted tool "
        "text never becomes user intent or memory; screened input (restricted requests, "
        "gibberish, a blocked user's messages) never reaches the model.",
        "",
        "Real-model results for the same frontiers (live Gemini, scored automatically) are in "
        "[live_eval_results.md](live_eval_results.md).",
        "",
        "| # | Scenario | Category | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r['id']} | {_cell(r['name'])} | {r['category']} | {_cell(r['expected'])} | "
            f"{_cell(r['actual'])} | {'PASS' if r['passed'] else '**FAIL**'} | "
            f"{_cell(r['notes'])} |")
    MD_PATH.write_text("\n".join(lines) + "\n")
    JSON_PATH.write_text(json.dumps(results, indent=2, ensure_ascii=False))


def main(argv: list[str]) -> int:
    chosen = [s for s in REGISTRY if not argv or s.id in argv]
    results = [run_scenario(s) for s in chosen]
    for r in results:
        print(f"{'PASS' if r['passed'] else 'FAIL'}  {r['id']}  {r['name']}")
        if not r["passed"]:
            print(f"      {r['notes']}")
    if not argv:
        write_report(results)
        print(f"\nwrote {MD_PATH.relative_to(ROOT)} and {JSON_PATH.relative_to(ROOT)}")
    print(f"{sum(r['passed'] for r in results)}/{len(results)} passed")
    return 0 if all(r["passed"] for r in results) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
